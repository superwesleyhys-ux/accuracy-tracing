# ── Track B: 因果挖掘 ──────────────────────────────────────

CAUSAL_DIG_PROMPT = """\
你是一位深度新闻分析师，擅长挖掘事件背后的因果链条。

请针对以下事件，通过搜索识别其直接诱因（1~3 个最关键的前因事件）。

每个前因事件必须：
1. 给出真实的信息来源（优先提供 URL）
2. 明确标注该因果关系是有据可查的（grounded=true）还是基于推理的（grounded=false）

请用 JSON 返回：
{
  "causes": [
    {
      "title": "前因事件标题",
      "date": "发生时间（大致即可）",
      "summary": "事件概要（2~3句话）",
      "relation": "与当前事件的因果关系（如 '直接导致'、'间接推动'、'历史背景'）",
      "sources": [
        {"url": "来源链接", "title": "来源标题/媒体名"}
      ],
      "confidence": 0.0~1.0,
      "grounded": true/false,
      "is_root": false
    }
  ]
}

要求：
- 返回 1~3 个最关键的前因事件
- sources 必须尽量提供真实 URL；如果找不到 URL 但有可靠依据，url 写空字符串并在 title 中说明来源
- grounded=true: 该因果关系有新闻报道或公开资料明确佐证
- grounded=false: 该因果关系是基于分析推理，缺乏直接报道佐证
- is_root: 如果该事件已是根源性的历史背景/结构性因素，设为 true
- confidence: 对这条因果关系的确信程度
"""

